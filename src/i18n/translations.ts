import type { Lang } from '../types';

export function tField<T extends Record<string, unknown>>(obj: T | null | undefined, base: string, lang: Lang): string {
  if (!obj) return '';
  const val = obj[`${base}_${lang}`] ?? obj[`${base}_ar`] ?? obj[base];
  return typeof val === 'string' ? val : String(val ?? '');
}

